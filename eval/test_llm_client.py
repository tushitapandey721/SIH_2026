"""Test suite for LLM client with Groq primary and Mistral fallback."""

import sys
import os
from unittest.mock import patch

# Ensure utf-8 output encoding on Windows consoles
if sys.platform.startswith("win"):
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")

# Ensure project root is in sys.path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from app.llm.client import get_completion


def test_llm_client_live():
    """Performs a live call using get_completion."""
    print("=" * 60)
    print("Running Live LLM Client Test...")
    print("=" * 60)

    system_prompt = "You are IP-SAKTI Sahayak, an AI assistant for Ayurvedic IP and Regulatory Affairs. Be concise."
    user_prompt = "What is Section 3(p) of the Indian Patents Act 1970 in one sentence?"

    try:
        result = get_completion(
            system_prompt=system_prompt,
            user_prompt=user_prompt,
            max_tokens=256,
        )
        print("\n--- Live Test Result ---")
        print(f"Provider Used : {result['provider_used']}")
        print(f"Response Text : {result['text']}")
        assert "text" in result and len(result["text"]) > 0
        assert result["provider_used"] in ("groq", "mistral")
        print("\n[SUCCESS] Live call completed successfully!")
    except Exception as e:
        print(f"\n[INFO] Live API call did not succeed (likely missing/invalid API keys in environment): {e}")


def test_fallback_mechanism():
    """Simulates Groq error to test automated fallback to Mistral."""
    print("\n" + "=" * 60)
    print("Testing Automated Fallback Mechanism (Mocked Groq Failure)...")
    print("=" * 60)

    with patch("app.llm.client._call_groq") as mock_groq, \
         patch("app.llm.client._call_mistral") as mock_mistral:

        # Simulate Groq error
        mock_groq.side_effect = RuntimeError("Groq Rate Limit Reached (429)")
        mock_mistral.return_value = "Section 3(p) excludes traditional knowledge from patentability."

        result = get_completion(
            system_prompt="Test system prompt",
            user_prompt="Test query",
            max_tokens=100,
        )

        print(f"Result Provider: {result['provider_used']}")
        print(f"Result Text    : {result['text']}")

        assert result["provider_used"] == "mistral"
        assert "traditional knowledge" in result["text"].lower()
        mock_groq.assert_called_once()
        mock_mistral.assert_called_once()
        print("\n[SUCCESS] Fallback to Mistral on Groq error verified!")


def test_groq_success():
    """Simulates Groq success without calling Mistral."""
    print("\n" + "=" * 60)
    print("Testing Primary Groq Path (Mocked Groq Success)...")
    print("=" * 60)

    with patch("app.llm.client._call_groq") as mock_groq, \
         patch("app.llm.client._call_mistral") as mock_mistral:

        mock_groq.return_value = "Response generated by Groq gpt-oss-120b."

        result = get_completion(
            system_prompt="Test system",
            user_prompt="Test user query",
            max_tokens=100,
        )

        print(f"Result Provider: {result['provider_used']}")
        print(f"Result Text    : {result['text']}")

        assert result["provider_used"] == "groq"
        assert result["text"] == "Response generated by Groq gpt-oss-120b."
        mock_groq.assert_called_once()
        mock_mistral.assert_not_called()
        print("\n[SUCCESS] Groq primary path verified without calling Mistral!")


if __name__ == "__main__":
    test_groq_success()
    test_fallback_mechanism()
    test_llm_client_live()
